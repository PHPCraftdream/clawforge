// docs/guide/commands.md's command table and README.md's command list are generated from the
// one command registry (entry/registry.ts's surfaceRegistry) — the declarations `--help`, the MCP
// schemas and shell completion read — so neither page can name a command or an argument the tool
// does not accept. Each block between its markers must equal tools/dev/docs-commands.ts's output
// byte for byte:
// a hand edit, or a declaration the page never followed, fails here, and the fix is to
// regenerate, never to patch a cell.

import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { monorepoRoot } from "#framework/core/env.ts";
import { surfaceRegistry } from "#framework/entry/registry.ts";
import { README_BEGIN, README_END, renderCommandList, renderCommandTables } from "#tools/dev/docs-commands.ts";
import { check, finish } from "#checks/kit/harness.ts";

const BEGIN = "<!-- commands:begin (generated by npm run docs:commands from the command declarations; do not edit) -->";
const END = "<!-- commands:end -->";
const REGENERATE = "run npm run docs:commands";
const ROW = /^\| `([a-z][a-z-]*)` \|/;

const page = (await readFile(resolve(monorepoRoot, "docs", "guide", "commands.md"), "utf8")).replaceAll("\r\n", "\n");

check("the page carries exactly one begin marker and one end marker", [page.split(BEGIN).length - 1, page.split(END).length - 1], [1, 1]);

const block = page.slice(page.indexOf(BEGIN) + BEGIN.length, page.indexOf(END)).trim();
check(`the committed block is byte-identical to the generated table (${REGENERATE})`, block, renderCommandTables().trim());

const rows = block.split("\n").filter((line) => ROW.test(line)).map((line) => ROW.exec(line)?.[1] ?? "");
check("every registry entry is one row of the table, and nothing else is", [...rows].sort(), [...surfaceRegistry().names].sort());

const readme = (await readFile(resolve(monorepoRoot, "README.md"), "utf8")).replaceAll("\r\n", "\n");
check("README carries exactly one command-list begin marker and one end marker", [readme.split(README_BEGIN).length - 1, readme.split(README_END).length - 1], [1, 1]);
const list = readme.slice(readme.indexOf(README_BEGIN) + README_BEGIN.length, readme.indexOf(README_END)).trim();
check(`README's command list is byte-identical to the generated one (${REGENERATE})`, list, renderCommandList().trim());

finish("docs-commands");